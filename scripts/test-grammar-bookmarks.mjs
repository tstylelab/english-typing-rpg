import assert from 'node:assert/strict';
import { load } from './lib/load-typescript-data.mjs';
const { grammarBookmarkKey, readGrammarBookmarks, toggleGrammarBookmark } = load('src/grammarBookmarks.ts');
const data = new Map();
const storage = { getItem:key => data.get(key) ?? null, setItem:(key,value) => data.set(key,value) };
const ids = player => Array.from(readGrammarBookmarks(storage,player));
assert.deepEqual(ids('one'),[]);
toggleGrammarBookmark(storage,'one','be');
toggleGrammarBookmark(storage,'one','can');
assert.deepEqual(ids('one'),['be','can']);
assert.deepEqual(ids('two'),[]);
toggleGrammarBookmark(storage,'two','past');
toggleGrammarBookmark(storage,'one','be');
assert.deepEqual(ids('one'),['can']);
assert.deepEqual(ids('two'),['past']);
assert.throws(() => toggleGrammarBookmark(storage,'','be'));
assert.throws(() => toggleGrammarBookmark(storage,'one','unknown'));
data.set(grammarBookmarkKey('one'),'["can","can",123,"unknown"]');
assert.deepEqual(ids('one'),['can']);
data.set(grammarBookmarkKey('one'),'{broken');
assert.throws(() => toggleGrammarBookmark(storage,'one','be'));
assert.equal(data.get(grammarBookmarkKey('one')),'{broken','Do not overwrite unreadable stored data');
data.set(grammarBookmarkKey('one'),'{}');
assert.throws(() => readGrammarBookmarks(storage,'one'));
assert.throws(() => toggleGrammarBookmark({...storage,setItem:() => {throw new Error('quota');}},'two','be'));
assert.deepEqual(ids('two'),['past'],'Failed write leaves saved cards unchanged');
// Simulate a second caller saving a card before the first toggles another.
toggleGrammarBookmark(storage,'two','can');
toggleGrammarBookmark(storage,'two','noun');
assert.deepEqual(ids('two'),['past','can','noun']);
assert.notEqual(grammarBookmarkKey('a:b'),grammarBookmarkKey('a%3Ab'));
const grade5Before=data.get(grammarBookmarkKey('two'));
assert.equal(grammarBookmarkKey('two'),'etyping_grammar_bookmarks_v1:two:Eiken5','Keep published Grade 5 storage key');
assert.notEqual(grammarBookmarkKey('two','Eiken4'),grammarBookmarkKey('two'));
toggleGrammarBookmark(storage,'two','can','Eiken4');
toggleGrammarBookmark(storage,'two','as','Eiken4');
assert.deepEqual(Array.from(readGrammarBookmarks(storage,'two','Eiken4')),['can','as']);
toggleGrammarBookmark(storage,'two','can','Eiken4');
assert.deepEqual(Array.from(readGrammarBookmarks(storage,'two','Eiken4')),['as']);
assert.equal(data.get(grammarBookmarkKey('two')),grade5Before,'Grade 4 writes preserve Grade 5 even for shared card IDs');
assert.deepEqual(Array.from(readGrammarBookmarks(storage,'another','Eiken4')),[]);
assert.throws(()=>toggleGrammarBookmark(storage,'two','be','Eiken4'),'Reject cards from another course');
data.set(grammarBookmarkKey('two','Eiken4'),'broken');
assert.throws(()=>toggleGrammarBookmark(storage,'two','as','Eiken4'));
assert.equal(data.get(grammarBookmarkKey('two','Eiken4')),'broken');
assert.equal(data.get(grammarBookmarkKey('two')),grade5Before);
console.log('PASS: bookmarks add/remove, player/course isolation, Grade 5 storage compatibility, fresh reads, bounded IDs, corruption and unavailable storage');
